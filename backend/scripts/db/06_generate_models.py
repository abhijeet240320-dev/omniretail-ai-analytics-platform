"""Generate the SQLAlchemy 2.x models from the LIVE PostgreSQL catalog.

USAGE (from the repository root)
--------------------------------
    .venv/Scripts/python.exe backend/scripts/db/06_generate_models.py
    .venv/Scripts/python.exe backend/scripts/db/06_generate_models.py --check

WHY GENERATE INSTEAD OF HAND-WRITING
------------------------------------
Thirty tables, 106,7 million rows and 46 constraints were loaded by a script
that MEASURED what the data supported. Writing the models by hand would mean a
human re-deciding all of that by eye, and the two would drift the first time
somebody added a column. These models are reflected from the same catalog the
data was loaded into, so they cannot disagree with it.

One file per source schema (olist.py, dataco.py, dunnhumby.py, m5.py) rather
than one big models.py, for the same reason backend/sql/ is organised per source:
the layer should make it awkward to treat two companies' tables as one thing.

WHAT IT DOES NOT DO
-------------------
It does not invent anything. Column types come from the catalog, nullability
comes from the catalog, primary keys come from the catalog, and a table with no
primary key (dunnhumby.coupon_redemptions, whose candidate key the real rows
refused) is emitted without one rather than given a synthetic surrogate.

--check exits non-zero if the generated files on disk differ from what the
catalog would produce, which is what makes "the models match the database" a
checkable statement instead of an aspiration.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO_ROOT / "backend"))

from sqlalchemy import create_engine, inspect  # noqa: E402
from sqlalchemy.engine import Inspector  # noqa: E402

from app.core.config import get_settings  # noqa: E402

MODELS_DIR = REPO_ROOT / "backend" / "app" / "models"
SOURCES = ("olist", "dataco", "dunnhumby", "m5")

# Keyed on the SQLAlchemy type class that reflection returns, not on the
# PostgreSQL type name. Only the seven types this database actually uses are
# listed. An unmapped type is an error rather than a silent fallback to String,
# because a wrong type that imports cleanly is worse than one that refuses.
#
# NUMERIC keeps its precision and scale (18,4 and 10,4 are both present) because
# dropping them would make alembic report a type change on a table where nothing
# changed. DOUBLE PRECISION maps to Double(), not Float(), so the rendered DDL
# is byte-identical to what the loader created.
TYPE_MAP = {
    "TEXT": "Text()",
    "BIGINT": "BigInteger()",
    "SMALLINT": "SmallInteger()",
    "INTEGER": "Integer()",
    "BOOLEAN": "Boolean()",
    "TIMESTAMP": "DateTime()",
    "TIMESTAMP_WITH_TIMEZONE": "DateTime(timezone=True)",
    "DOUBLE_PRECISION": "Double()",
    "DATE": "Date()",
}

# The import name for each rendered type, so the generated file imports exactly
# what it uses and nothing else.
TYPE_CLASS_NAMES = {
    "Text", "BigInteger", "SmallInteger", "Integer", "Boolean",
    "DateTime", "Double", "Date", "Numeric",
}

HEADER = '''"""SQLAlchemy models for the {schema} schema.

GENERATED by backend/scripts/db/06_generate_models.py - DO NOT EDIT BY HAND.
Run that script (or `... --check`) to regenerate or verify this file.

{domain}

READING THE FKs: every foreign key in this file points inside the {schema}
schema. That is not a coincidence, it is the project's central rule - these are
{schema} rows and nobody else's, so a relationship that reached another schema
could not be expressed even by accident.
"""
'''


def column_type(column, qualified: str) -> str:
    """Render one column's SQLAlchemy type.

    `qualified` is used only for the error message, so an unmapped type names the
    column that caused it rather than stopping with no clue.
    """
    reflected = column["type"]
    key = type(reflected).__name__.upper()
    if key == "NUMERIC":
        # precision/scale are load-bearing here - see TYPE_MAP.
        if reflected.precision is None:
            return "Numeric()"
        return f"Numeric({reflected.precision}, {reflected.scale})"
    rendered = TYPE_MAP.get(key)
    if rendered is None:
        raise SystemExit(
            f"unmapped PostgreSQL type {key!r} on {qualified}.{column['name']} - "
            "add it to TYPE_MAP rather than guessing, because a wrong type "
            "imports cleanly and lies later"
        )
    return rendered


def build_core_table(schema: str, table: str, inspector: Inspector) -> str:
    """Emit a Core Table for a table the ORM cannot map.

    dunnhumby.coupon_redemptions has NO primary key: the candidate key
    (household_key, day, coupon_upc) was tested against the real rows and
    rejected, because 14 rows genuinely repeat it. SQLAlchemy's ORM refuses to
    map a class with no primary key, and the obvious workaround - declaring a
    surrogate key so the mapper is happy - would be inventing an identity the
    data explicitly refused to support.

    So this table is declared as a Core Table instead. It still lives in
    Base.metadata, so Alembic still compares it and the drift check still sees
    it; it simply is not an ORM entity, because it does not have one.
    """
    columns = inspector.get_columns(table, schema=schema)
    lines = [
        f'# {schema}.{table} has NO primary key.',
        "#",
        "# The candidate key (household_key, day, coupon_upc) was tested against the",
        "# real rows and REJECTED: 14 rows genuinely repeat it. SQLAlchemy's ORM",
        "# cannot map a class without a primary key, and adding a surrogate would",
        "# fabricate an identity the data refused to support. It is therefore a Core",
        "# Table: fully available for queries and for Alembic, but not an ORM entity.",
        f'{table} = Table(',
        f'    "{table}",',
        "    Base.metadata,",
    ]
    for column in columns:
        rendered = column_type(column, f"{schema}.{table}")
        comment = ""
        if column.get("comment"):
            comment = f"  # {str(column['comment'])[:60]}"
        lines.append(
            f'    Column("{column["name"]}", {rendered}, '
            f"nullable={bool(column['nullable'])}),{comment}"
        )
    lines.append(f'    schema="{schema}",')
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def relationships_for(
    table: str, outgoing: dict[str, list], incoming: dict[str, list], module: str
) -> list[str]:
    """Emit the relationship attributes that belong to THIS class.

    Both halves of a relationship have to be declared on their own classes: the
    child gets `referred_parent`, the parent gets `child_rows`. Emitting the
    parent's half inside the child's class body - which is what a naive
    one-pass loop does - produces a class that declares an attribute belonging
    to a different model, and the mapper then fails with "Mapper[parent] has no
    property child_rows".

    Annotations are MODULE-QUALIFIED ("app.models.olist.orders"). That is not
    decoration: olist.orders and dataco.orders are different tables that happen
    to share a name, and a declarative registry keys classes by class name. An
    unqualified "orders" resolves ambiguously and the mapper refuses with
    "Multiple classes found for path orders". This is the project's per-source
    rule showing up in the ORM layer - four companies, four unrelated `orders`.
    """
    lines = [
        "    # Relationships (viewonly: loaded data, not application-owned).",
        "    # foreign_keys is inferred - there is exactly one FK per child/parent",
        "    # pair in this schema, which 06_generate_models.py checks before",
        "    # emitting. Both sides are viewonly so nothing here implies a write path.",
        "    # Annotations are module-qualified because table names repeat across",
        "    # sources (olist.orders and dataco.orders are unrelated tables).",
        "    # The parent side is named <child>_via_<fk_column>, not <child>_rows:",
        "    # dataco.order_items points at BOTH orders and products, so a name keyed",
        "    # on the child alone would be emitted twice and back_populates would",
        "    # point at the same attribute from two relationships.",
    ]
    for fk in outgoing.get(table, []):
        referred = fk["referred_table"]
        column = fk["constrained_columns"][0]
        lines.append(
            f'    referred_{referred}: Mapped["{module}.{referred}"] = relationship('
            f'back_populates="{table}_via_{column}", viewonly=True)'
        )
    for child, column in sorted(incoming.get(table, [])):
        # The partner of this attribute is the CHILD's relationship pointing back
        # here, and that relationship is named after the table it points at -
        # which is THIS table, not the child. Getting that backwards gives
        # "Mapper[customers] has no property referred_customers".
        lines.append(
            f'    {child}_via_{column}: Mapped[list["{module}.{child}"]] = relationship('
            f'back_populates="referred_{table}", viewonly=True)'
        )
    return lines


def build_model(
    schema: str,
    table: str,
    inspector: Inspector,
    outgoing: dict[str, list],
    incoming: dict[str, list],
    module: str,
) -> str:
    columns = inspector.get_columns(table, schema=schema)
    pk_info = inspector.get_pk_constraint(table, schema=schema) or {}
    pk_columns = pk_info.get("constrained_columns") or []
    pk_name = pk_info.get("name")
    uniques = inspector.get_unique_constraints(table, schema=schema)
    fks = inspector.get_foreign_keys(table, schema=schema)

    # Map each local column to the foreign key that points away from it, so the
    # ForeignKey can be declared on the column with its real name.
    fk_for_column = {
        name: fk for fk in fks for name in fk["constrained_columns"]
    }

    if not pk_columns:
        return build_core_table(schema, table, inspector)

    # Every relationship below relies on SQLAlchemy inferring the foreign key
    # from "there is exactly one FK between these two tables". That is true today;
    # if a future load adds a second FK between the same pair, inference becomes
    # ambiguous and the model would be silently wrong. Refuse instead.
    targets = [fk["referred_table"] for fk in fks]
    if len(targets) != len(set(targets)):
        raise SystemExit(
            f"{schema}.{table} has two foreign keys to the same table ({targets}). "
            "Relationship inference would be ambiguous; emit explicit foreign_keys "
            "for this table before regenerating."
        )

    table_args = []
    if pk_name and pk_columns:
        cols = ", ".join(f'"{c}"' for c in pk_columns)
        table_args.append(f'PrimaryKeyConstraint({cols}, name="{pk_name}")')
    for unique in uniques:
        cols = ", ".join(f'"{c}"' for c in unique["column_names"])
        name = unique.get("name")
        rendered = f'UniqueConstraint({cols}, name="{name}")' if name else f"UniqueConstraint({cols})"
        table_args.append(rendered)
    # The {"schema": ...} dict must be the LAST element: SQLAlchemy accepts only
    # one dict and only in final position, and rejects it anywhere else with a
    # "'SchemaItem' object expected, got {...}" error.
    schema_arg = f'{{"schema": "{schema}"}}'
    if not table_args:
        table_args = [schema_arg]
    else:
        table_args.append(schema_arg)

    lines = [f"class {table}(Base):", f'    __tablename__ = "{table}"']
    if len(table_args) == 1:
        lines.append(f"    __table_args__ = {table_args[0]}")
    else:
        lines.append("    __table_args__ = (")
        lines.extend(f"        {arg}," for arg in table_args)
        lines.append("    )")
    lines.append("")

    for column in columns:
        rendered = column_type(column, f"{schema}.{table}")
        head = rendered.split("(")[0]
        annotation = {
            "Text": "str", "BigInteger": "int", "SmallInteger": "int",
            "Integer": "int", "Boolean": "bool", "DateTime": "datetime",
            "Date": "date",
        }.get(head, "Decimal" if head == "Numeric" else "float")

        bits = [f'    {column["name"]}: Mapped[{annotation}] = mapped_column(']
        # The type has to come first: Column() takes the type as its first
        # positional argument and everything after it as SchemaItems.
        bits.append(f"        {rendered},")
        fk = fk_for_column.get(column["name"])
        if fk is not None:
            target = f'{fk["referred_schema"]}.{fk["referred_table"]}.{fk["referred_columns"][0]}'
            name = fk.get("name")
            bits.append(f'        ForeignKey("{target}", name="{name}"),')
        bits.append(f"        nullable={bool(column['nullable'])},")
        if column.get("comment"):
            comment = str(column["comment"]).replace('"', "'")
            bits.append(f'        comment="{comment}",')
        bits[-1] = bits[-1].rstrip(",")
        bits.append("    )")
        lines.append("\n".join(bits))
        lines.append("")

    # Relationships, declared on this class rather than inside whichever child
    # happens to reference it.
    lines.extend(relationships_for(table, outgoing, incoming, module))
    lines.append("")
    return "\n".join(lines)


def class_names(inspector: Inspector) -> dict[tuple[str, str], str]:
    return {(s, t): t for s in SOURCES for t in inspector.get_table_names(schema=s)}


def order_tables(schema: str, tables: list[str], inspector: Inspector) -> list[str]:
    """Order tables so a parent is always defined before its children.

    back_populates needs both ends of a relationship to be mappable at the time
    the first one is configured. Emitting tables alphabetically puts
    `closed_deals` before `mql`, and the mapper then fails with "Mapper[mql]
    has no property closed_deals_rows". Sorting by foreign key dependency fixes
    it at the source rather than dropping back_populates.

    Cycles are handled by falling back to the remaining tables in alphabetical
    order; there are none today, and a cycle would fail loudly at import time
    anyway rather than silently mis-join.
    """
    depends_on = {
        table: {
            fk["referred_table"]
            for fk in inspector.get_foreign_keys(table, schema=schema)
            if fk["referred_schema"] == schema and fk["referred_table"] != table
        }
        for table in tables
    }
    ordered: list[str] = []
    remaining = set(tables)
    while remaining:
        ready = sorted(t for t in remaining if not (depends_on[t] & remaining))
        if not ready:  # a cycle; emit the rest alphabetically and let import fail
            ready = sorted(remaining)
        for table in ready:
            ordered.append(table)
            remaining.discard(table)
    return ordered


def render(inspector: Inspector) -> dict[Path, str]:
    models = class_names(inspector)
    files: dict[Path, str] = {}
    del models  # class names are emitted module-qualified; this map is unused

    for schema in SOURCES:
        tables = order_tables(schema, sorted(inspector.get_table_names(schema=schema)), inspector)
        if not tables:
            continue

        # Build the relationship graph once so each class can emit both halves
        # of the relationships that touch it.
        outgoing: dict[str, list] = {}
        incoming: dict[str, list] = {t: [] for t in tables}
        module = f"app.models.{schema}"
        for child in tables:
            for fk in inspector.get_foreign_keys(child, schema=schema):
                if fk["referred_schema"] != schema:
                    raise SystemExit(
                        f"cross-schema foreign key found: {schema}.{child} -> "
                        f"{fk['referred_schema']}.{fk['referred_table']}. "
                        "This must never be modelled."
                    )
                outgoing.setdefault(child, []).append(fk)
                parent = fk["referred_table"]
                if parent in incoming:
                    incoming[parent].append((child, fk["constrained_columns"][0]))
        model_sources = [
            build_model(schema, t, inspector, outgoing, incoming, module)
            for t in tables
        ]
        joined = "\n".join(model_sources)

        # Only import the names the file actually uses. A fixed import block
        # would carry dead names, and dead imports in generated code rot badly:
        # the next edit to TYPE_MAP would leave them behind.
        sa_names = sorted(
            {
                name
                for name in TYPE_CLASS_NAMES
                if f"        {name}(" in joined or f"({name}(" in joined
            }
        )
        for extra, token in (
            ("Column", 'Column("'),
            ("Table", "Table("),
            ("ForeignKey", "ForeignKey("),
            ("PrimaryKeyConstraint", "PrimaryKeyConstraint("),
            ("UniqueConstraint", "UniqueConstraint("),
        ):
            if token in joined and extra not in sa_names:
                sa_names.append(extra)
        sa_names.sort()
        needs_decimal = "Numeric(" in joined
        needs_datetime = "DateTime(" in joined
        needs_date = "Date(" in joined

        body = [HEADER.format(schema=schema, domain=f"Schema: {schema}.")]
        body.append("from __future__ import annotations")
        body.append("")
        # These are real imports, not TYPE_CHECKING ones: with
        # `from __future__ import annotations` every annotation is a string, and
        # SQLAlchemy evaluates them against the module namespace to work out the
        # Python type. Hiding them behind `if False:` or TYPE_CHECKING makes the
        # annotation unresolvable and the model fails to import.
        if needs_datetime or needs_date:
            names = ", ".join(
                n for n, needed in (("date", needs_date), ("datetime", needs_datetime)) if needed
            )
            body.append(f"from datetime import {names}")
        if needs_decimal:
            body.append("from decimal import Decimal")
        body.append("")
        body.append("from sqlalchemy import " + ", ".join(sa_names))
        body.append("from sqlalchemy.orm import Mapped, mapped_column, relationship")
        body.append("")
        body.append("from app.database.base import Base")
        body.append("")
        body.append("")
        files[MODELS_DIR / f"{schema}.py"] = ("\n".join(body) + joined).rstrip() + "\n"

    init = [
        '"""Every OmniRetail model, importable from one place.',
        "",
        "GENERATED by backend/scripts/db/06_generate_models.py - DO NOT EDIT BY HAND.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from app.database.base import Base",
        "",
    ]
    for schema in SOURCES:
        init.append(f"from app.models import {schema}  # noqa: F401")
    init += [
        "",
        "__all__ = [",
        '    "Base",',
    ]
    for schema in SOURCES:
        init.append(f'    "{schema}",')
    init += [
        "]",
        "",
        "SOURCES = (" + ", ".join(f'"{s}"' for s in SOURCES) + ")",
        "",
    ]
    files[MODELS_DIR / "__init__.py"] = "\n".join(init)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate models from the catalog.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if the files on disk differ from the catalog",
    )
    args = parser.parse_args()

    settings = get_settings()
    engine = create_engine(settings.database_url, future=True)
    inspector = inspect(engine)

    print("OmniRetail model generator")
    print(f"  target: {settings.postgres_host}:{settings.postgres_port}/{settings.postgres_db}")
    print("=" * 70)

    generated = render(inspector)

    stale: list[Path] = []
    for path, content in generated.items():
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        if existing == content:
            print(f"  [ ok ] {path.relative_to(REPO_ROOT)} matches the catalog")
            continue
        stale.append(path)
        if args.check:
            print(f"  [DRIFT] {path.relative_to(REPO_ROOT)} differs from the catalog")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"  [wrote] {path.relative_to(REPO_ROOT)}")

    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    (MODELS_DIR / "__init__.py").touch(exist_ok=True)

    if args.check and stale:
        print(
            f"\n{len(stale)} file(s) are stale. Regenerate with:\n"
            "  .venv/Scripts/python.exe backend/scripts/db/06_generate_models.py"
        )
        return 1
    if args.check:
        print("\nall model files match the live catalog")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())