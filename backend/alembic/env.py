"""Alembic environment.

WHAT THIS FILE IS FOR
---------------------
Two jobs, and only two:

1. Give Alembic the models (`Base.metadata`) so autogenerate knows what the
   schema is supposed to look like.
2. Give Alembic a connection, built from the same `Settings` object as
   everything else in the project.

The comment in `alembic.ini` explains why no URL is stored there. This module
is the file that actually supplies one.

include_schemas=True IS MANDATORY HERE
--------------------------------------
Every one of the 30 tables lives in one of five named schemas. Alembic reflects
the DEFAULT schema (`public`) unless `include_schemas` is set, and all five of
ours would then be invisible. With it off, `compare_metadata` sees an empty
database plus 30 modelled tables and cheerfully proposes to create all of them
in `public`, cross-source, exactly the mistake the schema layout exists to
prevent. This flag is load-bearing, not a default worth keeping.

compare_type=True IS THE OTHER ONE
----------------------------------
Without it Alembic compares only constraint and column presence, so renaming
BIGINT -> NUMERIC(18,4) or swapping DOUBLE -> NUMERIC would pass review. Given
that these tables hold measured money values whose precision decisions are
documented, type drift is exactly the kind of thing that must fail loudly.

WHAT Alembic CANNOT SEE (measured, not assumed)
-----------------------------------------------
Alembic 1.20.0's autogenerate registry compares unique constraints, indexes,
foreign keys and check constraints. It has NO primary-key comparator: there is
no `compare_primary_key` anywhere in the package, so `create_primary_key` and
`drop_primary_key` can never appear in an autogenerated diff for a table that
already exists.

This matters for exactly one table in this project. `dunnhumby.coupon_redemptions`
has NO primary key, because its candidate key was rejected against the real
rows - 14 rows genuinely repeat it, and inventing a surrogate would fabricate an
identity the data refused to support. It is a Core `Table`, so SQLAlchemy gives
it an empty `PrimaryKeyConstraint()` in `table.constraints`. That phantom is
harmless (no DDL clause, and reflection of the keyless table produces the same
phantom on the other side of the comparison), but the deeper point is that an
empty autogenerate says nothing about primary keys in either direction.

So `alembic revision --autogenerate` returning no ops is NOT sufficient evidence
that the models match the database. The authoritative check is
`test_primary_keys_match` in backend/tests/test_models_match_catalog.py, which
compares every key column by column. If you are relying on Alembic to catch a
key change here, you are relying on something that does not exist.

include_object: WHAT IS DELIBERATELY IGNORED
--------------------------------------------
Two exclusions, both narrow:

* `alembic_version` - Alembic owns that table and manages it itself. Without the
  filter, a database that has been stamped makes every autogenerate want to drop
  it, which is nonsense.
* The `analytics` schema - it is currently empty, and it is reserved for the
  curated cross-source layer (Phase 9), which will be populated by explicit DDL
  rather than by ORM models. If those objects ever land here without models,
  autogenerate would otherwise try to DROP them, and a migration that deletes
  curated analytics data on a routine schema change is not a risk worth taking.
  The moment `analytics` gains ORM-mapped tables, delete this exclusion.

Everything else - all four source schemas - is compared in full.
"""

from __future__ import annotations

import sys
from logging.config import fileConfig
from pathlib import Path

from alembic import context
from sqlalchemy import engine_from_config, pool

# Alembic's `prepend_sys_path` in alembic.ini already does this, but only when
# the command is run from the repository root. Doing it here from the file's own
# location makes `alembic -c` work from any directory, and costs two lines.
REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT / "backend") not in sys.path:
    sys.path.insert(0, str(REPO_ROOT / "backend"))

from app.core.config import get_settings  # noqa: E402
from app.database.base import Base  # noqa: E402

# Importing the package registers all 30 tables on Base.metadata. Without this
# line the models would be absent and autogenerate would propose creating the
# entire schema from nothing.
import app.models  # noqa: E402,F401

# `app.api_keys` is modelled, but on its OWN declarative base - see the module
# docstring in app/models/api_keys.py for why sharing `Base` would break every
# generated relationship. It has to be listed here explicitly or autogenerate
# would propose dropping the table and both of its indexes. Alembic accepts a
# sequence of MetaData objects, so this compares the four source schemas and
# the application schema in one pass.
from app.models.api_keys import AppBase  # noqa: E402

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = [Base.metadata, AppBase.metadata]

# The version table lives in `public` and is created by Alembic itself.
version_table = "alembic_version"

# Schemas whose tables this project models. `analytics` is deliberately absent.
MODELLED_SCHEMAS = frozenset({"olist", "dataco", "dunnhumby", "m5"})


def get_url() -> str:
    """The one place a database URL enters Alembic.

    Read from Settings, which reads `.env`. Note this happens in both the online
    and offline paths: offline mode (`--sql`) still has to know which database it
    is generating SQL for.
    """
    return get_settings().database_url


def include_object(object_, name, type_, reflected, compare_to) -> bool:
    """Filter what autogenerate is allowed to consider.

    Signature note: this is a MigrationContext OPTION, not a `compare_metadata`
    keyword argument. Passing it to compare_metadata() raises TypeError. The
    five arguments are (object, name, type, reflected, compare_to).
    """
    if type_ == "table":
        if name == version_table:
            return False
        # reflected=True, compare_to=None means "in the database, not in the
        # models". For an unmodelled schema that is a curated-layer object, not
        # drift, and we must never emit a DROP for it.
        if reflected and compare_to is None:
            if getattr(object_, "schema", None) not in MODELLED_SCHEMAS:
                return False
    return True


def run_migrations_offline() -> None:
    """Emit SQL to stdout without connecting: `alembic upgrade head --sql`.

    Useful for handing a DBA the exact statements, and for reviewing a
    migration without touching a database.
    """
    context.configure(
        url=get_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        include_schemas=True,
        compare_type=True,
        include_object=include_object,
        version_table=version_table,
        # Without this, tables are emitted in alphabetical order and a
        # child-before-parent CREATE TABLE fails on the FK.
        render_as_batch=False,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Connect and run migrations against a live database."""
    configuration = config.get_section(config.config_ini_section) or {}
    configuration["sqlalchemy.url"] = get_url()

    connectable = engine_from_config(
        configuration,
        prefix="sqlalchemy.",
        # NullPool: migrations run once, from a script, in a short-lived
        # process. A pool here would just keep a connection open for nothing.
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            include_schemas=True,
            compare_type=True,
            include_object=include_object,
            version_table=version_table,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
